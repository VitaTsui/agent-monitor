/**
 * 斜杠命令的判据（发出去的那一刻用）。
 *
 * 为什么需要它：斜杠命令被 Claude Code CLI 自己吃掉，**既不会写进 jsonl 的 user
 * 记录，也不会进终端的 queued_inputs**（core 的 scanner 只收 queue-operation）。
 * 也就是说，它永远不会作为「真实消息」同步回网页。而网页的本地回显（乐观上屏的
 * 那条 user 气泡）设计上只有一条退场路径 —— 被同步回来的真实消息接管。两者一撞，
 * 斜杠命令的回显就成了永远撤不下去的孤儿气泡（`/clear` 之后最明显：新会话里孤零零
 * 挂着一条「/clear」）。所以这类输入压根不该建回显。
 *
 * 与 Composer 里那条 `/^\/(\S*)$/` 不是一回事，别合并：那条问的是「用户此刻正在
 * 打命令名吗」（用来弹命令菜单、取过滤词），这条问的是「这段已经定稿要发出去的
 * 文本是不是一条命令」。
 *
 * 判据是结构性的，不认具体命令名（命令表随模型/插件变，还允许发列表外的自定义
 * 命令，逐个名字比对必然漏）：
 *   - 单行。多行输入里就算首行是 `/xxx`，主体也是正文，按普通消息处理。
 *   - 首字符是 `/`，紧跟字母，命令名里只有 `[A-Za-z0-9_:-]`，然后是空白或结束。
 *     命令名里不含 `/`，所以绝对路径（`/Users/x/a.ts 看下这个`）不会被误判。
 *
 * 误判的代价是不对称的，所以判据偏向「宁可当成命令」：
 *   - 误判成命令（发的其实是普通文本）→ 只是少了一两秒的乐观回显，真实消息同步
 *     回来照样上屏，自己就好了。
 *   - 漏判（命令被当成普通文本）→ 一条永久孤儿气泡，只能清缓存才消得掉。
 */
const SLASH_COMMAND_RE = /^\/[A-Za-z][A-Za-z0-9_:-]*(?:\s|$)/;

/** 这段要发出的文本是不是一条斜杠命令（前后空白已在调用方 trim，这里再兜一次） */
export const isSlashCommand = (text: string): boolean => {
  const t = text.trim();
  return !t.includes("\n") && SLASH_COMMAND_RE.test(t);
};
